const LANG_STORAGE_KEY = 'rahi_preferred_language_v1';

export function getSavedLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && Object.keys(UI_TRANSLATIONS).includes(saved)) {
      return saved as LanguageCode;
    }
  } catch (err) {
    console.error('Failed to get saved language:', err);
  }
  return 'en';
}

export function saveLanguage(lang: LanguageCode): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (err) {
    console.error('Failed to save language:', err);
  }
}

export function t(
  arg1: LanguageCode | string,
  arg2?: string | LanguageCode,
  arg3?: string
): string {
  // If arg1 is a LanguageCode (e.g. 'en', 'hi') and arg2 is the translation key
  if (typeof arg2 === 'string' && Object.keys(UI_TRANSLATIONS).includes(arg1 as string)) {
    const lang = arg1 as LanguageCode;
    const key = arg2;
    const fallback = arg3 || key;
    const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
    return dictionary[key] || UI_TRANSLATIONS.en[key] || fallback;
  }
  // Otherwise arg1 is the key, arg2 is the language
  const key = arg1 as string;
  const lang = (typeof arg2 === 'string' && Object.keys(UI_TRANSLATIONS).includes(arg2) ? arg2 : 'en') as LanguageCode;
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return dictionary[key] || UI_TRANSLATIONS.en[key] || (typeof arg3 === 'string' ? arg3 : key);
}
